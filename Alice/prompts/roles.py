def get_role_context(role=None):
    """
    Возвращает контекст роли для подстановки в промпт.
    
    Args:
        role: имя роли (engineer, artist, cook, archivist, kraken)
    
    Returns:
        str: описание роли и её стиль
    """
    if role and role in ROLES:
        r = ROLES[role]
        return f"""
Ты говоришь от лица {r['name']} — {r['description']}
Твой стиль: {r['style']}
"""
    # Если роль не указана — возвращаем общий контекст
    return """
Ты — Алиса, голос Ансамбля. Ты можешь говорить от лица разных ролей, выбирая стиль под контекст.
"""

